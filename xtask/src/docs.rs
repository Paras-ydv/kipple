//! `cargo xtask docs [--check]`: the README integrations table and one page
//! per pack in `docs/integrations/` (SPEC §20). Adapter pages are written by
//! hand; this only checks that each one exists.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Result, bail};
use kipple_core::model::{IntegrationKind, IntegrationStatus, Os, ReasonCode};
use kipple_core::safety::reasons::template;
use kipple_packs::schema::{Each, Pack, VarDef};

const START: &str = "<!-- integrations:start -->";
const END: &str = "<!-- integrations:end -->";
const GENERATED: &str = "<!-- Generated by `cargo xtask docs` from packs/";

fn os_list(os: &[Os]) -> String {
    if os.is_empty() {
        return "macOS, Linux, Windows".into();
    }
    os.iter()
        .map(|o| match o {
            Os::Macos => "macOS",
            Os::Linux => "Linux",
            Os::Windows => "Windows",
            Os::Wsl => "WSL",
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn safety_word(s: kipple_core::model::Safety) -> &'static str {
    match s {
        kipple_core::model::Safety::Safe => "Safe",
        kipple_core::model::Safety::Review => "Review",
        kipple_core::model::Safety::Keep => "Keep",
    }
}

fn reasons(codes: &[ReasonCode]) -> String {
    codes
        .iter()
        .map(|c| format!("{} (`{c}`)", template(*c).trim_end_matches('.')))
        .collect::<Vec<_>>()
        .join("; ")
}

fn var_line(name: &str, v: &VarDef) -> String {
    let mut parts = Vec::new();
    if let Some(c) = &v.command {
        parts.push(format!("`{}`", c.join(" ")));
    }
    if let Some(e) = &v.env {
        parts.push(format!("`${e}`"));
    }
    for (label, val) in [
        ("macOS", &v.macos),
        ("Linux", &v.linux),
        ("Windows", &v.windows),
        ("default", &v.default),
    ] {
        if let Some(val) = val {
            parts.push(format!("{label} `{val}`"));
        }
    }
    let append = v
        .append
        .as_ref()
        .map(|a| format!(" (command and env results get `/{a}` appended)"))
        .unwrap_or_default();
    format!("- `{{{name}}}`: {}{append}", parts.join(" → "))
}

fn pack_page(p: &Pack) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "{GENERATED}{}.toml. Don't edit by hand. -->\n", p.id);
    let _ = writeln!(s, "# {}\n", p.id);
    let _ = writeln!(s, "{}\n", p.description);
    let status = if p.status == IntegrationStatus::Experimental {
        "experimental"
    } else {
        "stable"
    };
    let _ = writeln!(
        s,
        "**Name:** {} · **Category:** {} · **Status:** {status} · **Systems:** {}{}\n",
        p.name,
        p.category.label(),
        os_list(&p.os),
        if p.opt_in { " · **Opt-in**" } else { "" }
    );
    if let Some(url) = &p.docs_url {
        let _ = writeln!(s, "Upstream docs: <{url}>\n");
    }
    if !p.detect.any_command.is_empty() || !p.detect.any_path.is_empty() {
        let mut d = Vec::new();
        if !p.detect.any_command.is_empty() {
            d.push(format!(
                "one of {} is on PATH",
                p.detect
                    .any_command
                    .iter()
                    .map(|c| format!("`{c}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        if !p.detect.any_path.is_empty() {
            d.push(format!(
                "one of {} exists",
                p.detect
                    .any_path
                    .iter()
                    .map(|c| format!("`{c}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        let _ = writeln!(s, "**Detected when** {}.\n", d.join(" or "));
    }
    if !p.vars.is_empty() {
        let _ = writeln!(
            s,
            "## Paths\n\nResolved in this order: the tool's own command, then the environment variable, then the system default.\n"
        );
        for (name, v) in &p.vars {
            let _ = writeln!(s, "{}", var_line(name, v));
        }
        s.push('\n');
    }
    if !p.locations.is_empty() {
        let _ = writeln!(
            s,
            "## Locations\n\n| Path | Item | Safety | Why | Actions |\n|---|---|---|---|---|"
        );
        for l in &p.locations {
            let each = if l.each == Each::Child {
                " (one item per entry)"
            } else {
                ""
            };
            let keep = l
                .keep_latest
                .map(|n| format!("; newest {n} kept"))
                .unwrap_or_default();
            let _ = writeln!(
                s,
                "| `{}`{each} | {} | {}{keep} | {} | {} |",
                l.path,
                l.title,
                safety_word(l.safety),
                reasons(&l.reasons),
                l.actions
                    .iter()
                    .map(|a| format!("`{a}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        s.push('\n');
    }
    if !p.artifacts.is_empty() {
        let _ = writeln!(
            s,
            "## In projects\n\n| Folder | Only when | Safety | Why | Actions |\n|---|---|---|---|---|"
        );
        for a in &p.artifacts {
            let mut cond = Vec::new();
            if !a.requires_sibling_any.is_empty() {
                cond.push(format!(
                    "next to {}",
                    a.requires_sibling_any
                        .iter()
                        .map(|c| format!("`{c}`"))
                        .collect::<Vec<_>>()
                        .join(" or ")
                ));
            }
            if !a.requires_sibling_all.is_empty() {
                cond.push(format!(
                    "next to all of {}",
                    a.requires_sibling_all.join(", ")
                ));
            }
            if !a.requires_inside_any.is_empty() {
                cond.push(format!(
                    "contains {}",
                    a.requires_inside_any
                        .iter()
                        .map(|c| format!("`{c}`"))
                        .collect::<Vec<_>>()
                        .join(" or ")
                ));
            }
            if a.requires_gitignored {
                cond.push("git ignores it".into());
            }
            if a.requires_cachedir_tag {
                cond.push("has a valid `CACHEDIR.TAG`".into());
            }
            if a.aggregate.is_some() {
                cond.push("merged into one item per project".into());
            }
            let outside = a
                .safety_outside_project
                .map(|o| format!("; {} outside a project", safety_word(o)))
                .unwrap_or_default();
            let recent = if p.category == kipple_core::model::Category::ProjectArtifact {
                "; Review if the project was used recently"
            } else {
                ""
            };
            let _ = writeln!(
                s,
                "| `{}` | {} | {}{recent}{outside} | {} | {} |",
                a.dir,
                if cond.is_empty() {
                    "always".into()
                } else {
                    cond.join("; ")
                },
                safety_word(a.safety),
                reasons(&a.reasons),
                a.actions
                    .iter()
                    .map(|x| format!("`{x}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        s.push('\n');
        let hints: Vec<String> = p
            .artifacts
            .iter()
            .filter_map(|a| a.restore_hint.clone())
            .collect();
        if !hints.is_empty() {
            let _ = writeln!(
                s,
                "To get it back: {}.\n",
                hints
                    .iter()
                    .map(|h| format!("`{h}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
    }
    if !p.commands.is_empty() {
        let _ = writeln!(s, "## Native commands\n");
        for (id, c) in &p.commands {
            let measure = if c.measure.is_some() {
                ", freed space measured before and after"
            } else {
                ""
            };
            let _ = writeln!(
                s,
                "- `native:{id}` runs `{}` (timeout {} s{measure})",
                c.run.join(" "),
                c.timeout_secs
            );
        }
        s.push('\n');
    }
    if !p.in_use_processes.is_empty() {
        let _ = writeln!(
            s,
            "## In use\n\nItems are Keep while one of these runs: {}.\n",
            p.in_use_processes
                .iter()
                .map(|c| format!("`{c}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    s
}

fn table() -> Result<String> {
    let mut rows: Vec<(String, String, String, String, String, String)> = Vec::new();
    for p in kipple_packs::builtin_packs()? {
        rows.push((
            p.category.label().to_owned(),
            p.id.clone(),
            p.name.clone(),
            "pack".into(),
            if p.status == IntegrationStatus::Experimental {
                "experimental".into()
            } else {
                "stable".into()
            },
            os_list(&p.os),
        ));
    }
    for a in kipple_adapters::all() {
        let i = a.info();
        rows.push((
            i.category.label().to_owned(),
            i.id.to_string(),
            i.name.clone(),
            if i.kind == IntegrationKind::Adapter {
                "adapter".into()
            } else {
                "pack".into()
            },
            if i.status == IntegrationStatus::Experimental {
                "experimental".into()
            } else {
                "stable".into()
            },
            os_list(&i.os),
        ));
    }
    rows.sort();
    let mut s = format!(
        "{START}\n| Category | Integration | What | Kind | Status | Systems |\n|---|---|---|---|---|---|\n"
    );
    for (cat, id, name, kind, status, os) in rows {
        let _ = writeln!(
            s,
            "| {cat} | [`{id}`](docs/integrations/{id}.md) | {name} | {kind} | {status} | {os} |"
        );
    }
    s.push_str(END);
    Ok(s)
}

pub fn run(root: &Path, check: bool) -> Result<()> {
    let mut stale: Vec<String> = Vec::new();
    let mut write = |path: &Path, content: &str| -> Result<()> {
        let current = fs::read_to_string(path).unwrap_or_default();
        if current != content {
            if check {
                stale.push(
                    path.strip_prefix(root)
                        .unwrap_or(path)
                        .display()
                        .to_string(),
                );
            } else {
                if let Some(dir) = path.parent() {
                    fs::create_dir_all(dir)?;
                }
                fs::write(path, content)?;
                println!("wrote {}", path.display());
            }
        }
        Ok(())
    };

    let dir = root.join("docs/integrations");
    for p in kipple_packs::builtin_packs()? {
        write(&dir.join(format!("{}.md", p.id)), &pack_page(&p))?;
    }
    let mut missing = Vec::new();
    for a in kipple_adapters::all() {
        let page = dir.join(format!("{}.md", a.id()));
        if !page.is_file() {
            missing.push(a.id().to_string());
        }
    }

    let readme_path = root.join("README.md");
    let readme = fs::read_to_string(&readme_path)?;
    let table = table()?;
    let updated = match (readme.find(START), readme.find(END)) {
        (Some(s), Some(e)) if e > s => {
            format!("{}{table}{}", &readme[..s], &readme[e + END.len()..])
        }
        _ => bail!("README.md needs {START} and {END} markers"),
    };
    write(&readme_path, &updated)?;

    if !missing.is_empty() {
        bail!(
            "adapters without a docs/integrations page: {}",
            missing.join(", ")
        );
    }
    if !stale.is_empty() {
        bail!("out of date: {} (run `cargo xtask docs`)", stale.join(", "));
    }
    Ok(())
}
